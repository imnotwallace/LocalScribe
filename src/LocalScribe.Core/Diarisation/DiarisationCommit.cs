using System.Globalization;
using LocalScribe.Core.Audio;
using LocalScribe.Core.Model;

namespace LocalScribe.Core.Diarisation;

/// <summary>The immutable result of one diarisation run, ready to merge into <c>speakers.json</c>
/// via <see cref="SpeakersMerge"/>. <see cref="Sources"/> names the re-diarised sides; cluster ids
/// restart at 0 each run, so clusterKeys are only unique within a single commit.</summary>
public sealed record DiarisationCommit(
    IReadOnlyList<SourceKind> Sources,
    IReadOnlyDictionary<string, IReadOnlyDictionary<string, string>> Assignments, // "Local"/"Remote" -> seq -> clusterKey
    IReadOnlyDictionary<string, string> Names,                                    // clusterKey -> displayName
    string Method,
    DateTimeOffset DiarisedAtUtc,
    IReadOnlyDictionary<string, SuggestionProvenanceEntry>? Provenance = null);   // clusterKey -> accepted suggestion

/// <summary>Default per-side display labels for freshly diarised clusters (before any manual
/// rename). Labels are 1-based and scoped per source, e.g. "Remote Speaker 1".</summary>
public static class DefaultSpeakerLabels
{
    // Enumerated (rather than hardcoding "Local"/"Remote") so a third SourceKind is understood by
    // IsMachineDefault the day it is added; cached because that runs per speakers.json entry.
    private static readonly SourceKind[] AllSources = Enum.GetValues<SourceKind>();

    /// <summary>The default label for cluster <paramref name="clusterId"/> (0-based) on
    /// <paramref name="source"/>, rendered 1-based, e.g. <c>For(Remote, 0)</c> => "Remote Speaker 1".</summary>
    public static string For(SourceKind source, int clusterId) =>
        $"{source} Speaker {clusterId + 1}";   // 1-based, per-side ("Local"/"Remote")

    /// <summary>True when <paramref name="name"/> is exactly the label THIS class would have
    /// generated for <paramref name="clusterKey"/> - i.e. nobody chose it (whole-branch review
    /// finding 1). The inverse is the only sound test for "a PERSON named this cluster":
    /// speakers.json Names is populated with <see cref="For"/> output by SpeakerDetectionStep on
    /// every auto-detected import, with no user interaction at all, so a non-empty Names map is
    /// evidence of a diarisation run, not of human review. The exported disclaimer variant is
    /// chosen from that count, and an untouched import was claiming "reviewed and corrected by a
    /// person" in a document served on the other side.
    ///
    /// It lives HERE, not at the counting call site in MaintenanceService.ProvenanceFor, because it
    /// needs both halves of one convention: how a clusterKey is spelled ("Source:id", minted by
    /// SpeakersMerge) and how a label is derived from it (<see cref="For"/>, right above). Splitting
    /// them across assemblies is how they would silently drift - and here the predicate is testable
    /// without a session on disk.
    ///
    /// UNRESOLVABLE keys (no ':', a non-integer or negative id, a source prefix this build does not
    /// know, a blank name) answer TRUE - "not a human act". That is the deliberately conservative
    /// direction for an evidentiary document: with no computable default, "differs from the default" is
    /// vacuously true, so answering FALSE would flip the disclaimer to "reviewed and corrected by a
    /// person" on the strength of a key nobody can interpret - the exact over-claim this predicate
    /// exists to stop. Under-counting instead leaves the UNTOUCHED sentence, and every clause of it
    /// ("generated by automated speech recognition", "may contain errors", "not a certified record")
    /// stays literally true even for a transcript a person did edit. One direction can print a
    /// falsehood; the other can only print less than the whole truth, and text corrections, splits
    /// and speaker pins each still flip the variant on their own. Never throws: an export must not
    /// fail on a hand-edited speakers.json.</summary>
    public static bool IsMachineDefault(string clusterKey, string name)
    {
        if (string.IsNullOrEmpty(clusterKey) || string.IsNullOrWhiteSpace(name)) return true;
        int colon = clusterKey.IndexOf(':');
        if (colon < 0) return true;
        // Invariant, like every other parse in the projection layer; NumberStyles.Integer so a
        // machine key can never be read through a culture's digit or sign conventions. A NEGATIVE
        // id is rejected with the unparseable ones rather than resolved: cluster ids are 0-based
        // and allocated as maxId+1, so no run ever mints one, and For() would answer "Speaker 0" -
        // a label no machine can produce, which would make every such key read as human-named.
        if (!int.TryParse(clusterKey.AsSpan(colon + 1), NumberStyles.Integer,
                CultureInfo.InvariantCulture, out int clusterId) || clusterId < 0)
            return true;
        var prefix = clusterKey.AsSpan(0, colon);
        // Matched against the enum's NAMES, not Enum.TryParse: TryParse also accepts the numeric
        // form, so a "0:1" key would resolve to Local and get a default label it never had.
        foreach (var source in AllSources)
            if (prefix.Equals(source.ToString(), StringComparison.Ordinal))
                return string.Equals(name, For(source, clusterId), StringComparison.Ordinal);
        return true;
    }
}
